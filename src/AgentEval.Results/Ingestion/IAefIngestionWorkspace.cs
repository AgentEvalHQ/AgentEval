namespace AgentEval.Results.Ingestion;

/// <summary>Owns an explicitly configured ingestion workspace, separate from source evidence and the viewer.</summary>
public interface IAefIngestionWorkspace : IDisposable
{
    /// <summary>The application-owned root. It must not be writable by untrusted local processes.</summary>
    string Root { get; }

    /// <summary>The directory for accepted runs; staging is never exposed as accepted evidence.</summary>
    string RunsDirectory { get; }

    /// <summary>
    /// Reserves a new staging directory. Retained stages, including those from interrupted processes,
    /// count toward capacity. This does not accept, verify, or index evidence.
    /// </summary>
    AefIngestionStage BeginStage(CancellationToken cancellationToken = default);

    /// <summary>Resolves an existing ordinary stage by its server-generated ID; refuses disposed ownership and links.</summary>
    AefIngestionStage OpenStage(string stageId);

    /// <summary>Resolves an ordinary accepted-run directory by its hash, without asserting its integrity.</summary>
    string OpenAcceptedRun(string runHash);

    /// <summary>
    /// Archives a completed control-only stage outside pending capacity. The caller owns the stage lease;
    /// this method releases it under workspace ownership before the directory move. Evidence is not deleted.
    /// </summary>
    bool ArchiveReceipt(string stageId, IDisposable stageLease);

    /// <summary>
    /// Atomically moves stage/content into runs/runHash without overwriting. The trusted caller must first verify
    /// the stage against this hash. This filesystem primitive does not perform protocol verification itself.
    /// </summary>
    string PublishVerifiedStage(string stageId, string runHash, CancellationToken cancellationToken = default);
}

/// <summary>A server-generated staging identity and its local directory; do not expose the path over HTTP.</summary>
/// <param name="Id">Opaque identity generated by the workspace.</param>
/// <param name="Directory">Application-owned local staging directory.</param>
public sealed record AefIngestionStage(string Id, string Directory);

/// <summary>Explicit storage configuration. Constructing options has no filesystem side effects.</summary>
public sealed class AefIngestionWorkspaceOptions
{
    /// <summary>Absolute, dedicated storage root. There is no current-directory or viewer-root fallback.</summary>
    public required string Root { get; init; }

    /// <summary>Maximum retained stages, including interrupted ones. Must be between 1 and 1024.</summary>
    public int MaxPendingStages { get; init; } = 64;

    /// <summary>Maximum accepted run directories, 1..100000. Default 1000. Existing entries count toward capacity.</summary>
    public int MaxAcceptedRuns { get; init; } = 1_000;

    /// <summary>Maximum archived receipt directories, 1..100000. Default 10000; receipts are never silently evicted.</summary>
    public int MaxArchivedReceipts { get; init; } = 10_000;
}
