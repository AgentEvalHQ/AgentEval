    [Theory]
    [MemberData(nameof(V019GoldenSelections))]
    public void DefaultOptions_DrawExactlyTheSampleV019Drew(
        int maxQuestions, bool stratified, int seed, string expectedIds)
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = maxQuestions,
            StratifiedSampling = stratified,
            RandomSeed = seed
        });

        Assert.Equal(expectedIds, string.Join(",", selected.Select(e => e.QuestionId)));
    }

    /// <summary>
    /// The shipped Subset preset draws no abstention question at all. Pinned because it is not
    /// visible in any configuration value: it is a property of one seed against one dataset.
    /// </summary>
    [Fact]
    public void SubsetPreset_DrawsZeroAbstentionQuestions()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = LongMemEvalBenchmark.SubsetMaxQuestions,
            StratifiedSampling = true,
            RandomSeed = 42
        });

        Assert.Equal(50, selected.Count);
        Assert.DoesNotContain(selected, e => e.IsAbstention);
        // And repeating the run does not widen coverage — a fixed seed re-draws the same questions,
        // so N runs measure one sample N times.
        var again = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = LongMemEvalBenchmark.SubsetMaxQuestions,
            StratifiedSampling = true,
            RandomSeed = 42
        });
        Assert.Equal(selected.Select(e => e.QuestionId), again.Select(e => e.QuestionId));
    }

    // ── Ask 1 proof: a requested type returns only that type ──────────────────

    [Fact]
    public void IncludeQuestionTypes_ReturnsOnlyTheRequestedTypeAndHonoursTheCount()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 30,
            IncludeQuestionTypes = [SingleSessionAssistant],
            RandomSeed = 42
        });

        // "30 single-session-assistant questions", not "50 of which 6 are".
        Assert.Equal(30, selected.Count);
        Assert.All(selected, e => Assert.Equal(SingleSessionAssistant, e.QuestionType));
    }

    [Fact]
    public void IncludeQuestionTypes_WithoutTheFilter_TheSameBudgetYieldsOnlySixOfThatType()
    {
        // The problem the filter solves, measured rather than asserted.
        var unfiltered = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 50,
            StratifiedSampling = true,
            RandomSeed = 42
        });

        Assert.Equal(6, unfiltered.Count(e => e.QuestionType == SingleSessionAssistant));
    }

    [Fact]
    public void IncludeQuestionTypes_MultipleTypes_StratifiesWithinThem()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 40,
            StratifiedSampling = true,
            IncludeQuestionTypes = [SingleSessionAssistant, TemporalReasoning],
            RandomSeed = 42
        });

        Assert.Equal(40, selected.Count);
        Assert.All(selected, e => Assert.Contains(e.QuestionType, new[] { SingleSessionAssistant, TemporalReasoning }));
        // Both requested types are represented — stratification still applies inside the filter.
        Assert.Contains(selected, e => e.QuestionType == SingleSessionAssistant);
        Assert.Contains(selected, e => e.QuestionType == TemporalReasoning);
    }

    [Fact]
    public void IncludeQuestionTypes_SameSeedReproducesTheSameSet()
    {
        static ExternalBenchmarkOptions Options() => new()
        {
            MaxQuestions = 25,
            IncludeQuestionTypes = [TemporalReasoning],
            RandomSeed = 1234
        };

        var first = Load(Options()).Select(e => e.QuestionId).ToArray();
        var second = Load(Options()).Select(e => e.QuestionId).ToArray();

        Assert.Equal(first, second);
    }

    [Fact]
    public void IncludeQuestionTypes_DifferentSeedDrawsADifferentSet()
    {
        var first = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 25,
            IncludeQuestionTypes = [TemporalReasoning],
            RandomSeed = 1
        }).Select(e => e.QuestionId).ToArray();

        var second = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 25,
            IncludeQuestionTypes = [TemporalReasoning],
            RandomSeed = 2
        }).Select(e => e.QuestionId).ToArray();

        Assert.NotEqual(first, second);
    }

