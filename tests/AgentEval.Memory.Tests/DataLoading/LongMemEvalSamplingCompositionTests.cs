/// <summary>
/// Sampling composition control: selecting question types, controlling abstention, and — above all —
/// proving that a run which asks for none of it still draws exactly the sample it drew before.
/// </summary>
/// <remarks>
/// <para>
/// Runs against <c>longmemeval-sampling-fixture.json</c>: the 500 real question ids and
/// question_type values of <c>longmemeval_s_cleaned.json</c>, in the dataset's own order, with no
/// question text, answers or haystack content. Sampling reads only type, id and order, so selection
/// here is identical to selection against the real file — while the real file stays gitignored and
/// these tests still run in CI.
/// </para>
/// </remarks>
public class LongMemEvalSamplingCompositionTests
{
    private const string SingleSessionAssistant = "single-session-assistant";
    private const string TemporalReasoning = "temporal-reasoning";

    private static string FixturePath()
        => Path.Combine(AppContext.BaseDirectory, "DataLoading", "longmemeval-sampling-fixture.json");

    private static IReadOnlyList<LongMemEvalEntry> Load(ExternalBenchmarkOptions options)
        => LongMemEvalDataLoader.LoadFromFile(FixturePath(), options);

    // ── The fixture itself ────────────────────────────────────────────────────

    [Fact]
    public void Fixture_MatchesTheRealDatasetShape()
    {
        var all = Load(new ExternalBenchmarkOptions());

        Assert.Equal(500, all.Count);
        Assert.Equal(30, all.Count(e => e.IsAbstention));
        // Six question types, and abstention is orthogonal to all of them — the property that makes
        // type stratification unable to say anything about abstention coverage.
        Assert.Equal(6, all.Select(e => e.QuestionType).Distinct().Count());
        Assert.All(all.Where(e => e.IsAbstention), e => Assert.DoesNotContain("_abs", e.QuestionType));
    }

