    [Fact]
    public void IncludeQuestionTypes_UnknownType_SelectsNothingRatherThanFallingBackToEverything()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 10,
            IncludeQuestionTypes = ["no-such-type"],
            RandomSeed = 42
        });

        // A typo must not quietly return a full-spectrum sample that then gets reported as per-type.
        Assert.Empty(selected);
    }

    // ── Ask 2 proof: abstention excluded / included / targeted ────────────────

    [Fact]
    public void AbstentionPolicy_Exclude_RemovesEveryAbstentionQuestion()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 50,
            AbstentionPolicy = AbstentionSamplingPolicy.Exclude,
            RandomSeed = 42
        });

        Assert.Equal(50, selected.Count);
        Assert.DoesNotContain(selected, e => e.IsAbstention);
    }

    [Fact]
    public void AbstentionPolicy_Only_SelectsAbstentionQuestionsExclusively()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 20,
            AbstentionPolicy = AbstentionSamplingPolicy.Only,
            RandomSeed = 42
        });

        Assert.Equal(20, selected.Count);
        Assert.All(selected, e => Assert.True(e.IsAbstention));
    }

    [Fact]
    public void AbstentionPolicy_Only_WithNoBudget_ReturnsAllThirty()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            AbstentionPolicy = AbstentionSamplingPolicy.Only
        });

        Assert.Equal(30, selected.Count);
        Assert.All(selected, e => Assert.True(e.IsAbstention));
    }

    [Theory]
    [InlineData(20, 0.5, 10, 10)]
    [InlineData(20, 0.25, 5, 15)]
    [InlineData(40, 0.1, 4, 36)]
    public void AbstentionPolicy_TargetProportion_SplitsTheBudgetAsRequested(
        int maxQuestions, double proportion, int expectedAbstention, int expectedOrdinary)
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = maxQuestions,
            AbstentionPolicy = AbstentionSamplingPolicy.TargetProportion,
            AbstentionTargetProportion = proportion,
            RandomSeed = 42
        });

        Assert.Equal(expectedAbstention, selected.Count(e => e.IsAbstention));
        Assert.Equal(expectedOrdinary, selected.Count(e => !e.IsAbstention));
    }

    [Fact]
    public void AbstentionPolicy_TargetProportion_ShortPool_IsLeftShortNotToppedUp()
    {
        // 80% of 100 is 80 abstention questions; only 30 exist. Topping up from the ordinary pool
        // would return a full 100 that quietly measured something else.
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 100,
            AbstentionPolicy = AbstentionSamplingPolicy.TargetProportion,
            AbstentionTargetProportion = 0.8,
            RandomSeed = 42
        });

        Assert.Equal(30, selected.Count(e => e.IsAbstention));
        Assert.Equal(20, selected.Count(e => !e.IsAbstention));
        Assert.Equal(50, selected.Count);
    }

    [Fact]
    public void AbstentionPolicy_ComposesWithTypeFilter()
    {
        var selected = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 20,
            IncludeQuestionTypes = [TemporalReasoning],
            AbstentionPolicy = AbstentionSamplingPolicy.Only,
            RandomSeed = 42
        });

        // temporal-reasoning holds 6 abstention questions, so the budget cannot be filled.
        Assert.Equal(6, selected.Count);
        Assert.All(selected, e =>
        {
            Assert.True(e.IsAbstention);
            Assert.Equal(TemporalReasoning, e.QuestionType);
        });
    }

    [Fact]
    public void AbstentionPolicy_AsSampled_IsTodayExactly()
    {
        var explicitPolicy = Load(new ExternalBenchmarkOptions
        {
            MaxQuestions = 50,
            RandomSeed = 42,
            AbstentionPolicy = AbstentionSamplingPolicy.AsSampled
        });

        var baseline = Load(new ExternalBenchmarkOptions { MaxQuestions = 50, RandomSeed = 42 });

        Assert.Equal(baseline.Select(e => e.QuestionId), explicitPolicy.Select(e => e.QuestionId));
    }

